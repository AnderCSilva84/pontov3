const test=require('node:test'),assert=require('node:assert/strict');
test('migração de grupo: inventário, manutenção, cópia e troca atômica preservam os dados e a ponte',{skip:!process.env.FIRESTORE_EMULATOR_HOST},async t=>{
 assert.ok(process.env.GCLOUD_PROJECT?.startsWith('demo-'));
 const admin=require('../functions/node_modules/firebase-admin');
 const app=admin.initializeApp({projectId:process.env.GCLOUD_PROJECT+'-migracao'},'grupos-migracao'),db=app.firestore();t.after(()=>app.delete());
 const {planejarMigracao,migrarLegado}=require('../functions/grupos-migracao.cjs');
 const {bancoDoUsuario,bancoDoGrupo}=require('../functions/grupos-contexto.cjs');
 const {createNoBolsoBridge}=require('../functions/no-bolso-bridge.cjs');
 const dados={titularUid:'legado-titular',grupoId:'casa-migrada',nomeGrupo:'Casa existente'};
 await db.doc('users/legado-titular').set({nome:'Titular fictício',role:'admin',ativo:true});
 await db.doc('users/legado-func').set({nome:'Funcionária fictícia',role:'funcionario',ativo:true,funcionarioId:'func-legada'});
 await db.doc('funcionarios/func-legada').set({nome:'Funcionária fictícia',ativo:true});
 await db.doc('dias/func-legada_2026-10-20').set({funcionarioId:'func-legada',entrada:'08:00'});
 await db.doc('comprasListas/compra').set({titulo:'Compra existente',status:'finalizada',finalizadaPor:'legado-titular',totalCentavos:5000,finalizadaEm:new Date('2026-10-20T12:00:00Z')});
 await db.doc('comprasListas/compra/itens/arroz').set({nomeSnapshot:'Arroz',estado:'comprado',totalCentavos:5000});
 await db.doc('lembretes/cuidado').set({titulo:'Cuidado fictício'});await db.doc('lembretes/cuidado/ocorrencias/dose').set({status:'concluido',concluidoPor:'legado-func'});
 const bridge=createNoBolsoBridge({db,pilotUid:'target-mig',bancoDaOrigem:uid=>bancoDoUsuario(db,uid),assertAuthUser:async()=>{}});
 const codigo=await bridge.grantFor('legado-titular');await bridge.redeem('target-mig',codigo.code);
 assert.equal((await bridge.summary('target-mig','2026-10')).months.find(m=>m.month==='2026-10').totalCentavos,5000);
 const plano=await planejarMigracao(db,dados);
 assert.equal(plano.contas,2);assert.equal(plano.documentos,8);
 assert.equal((await db.collection('grupos').get()).size,0);assert.equal((await db.collection('vinculosUsuarios').get()).size,0);
 await assert.rejects(migrarLegado(db,dados,{confirmarAssinatura:'errada',quiescenciaMs:0}),/assinatura/);
 await assert.rejects(migrarLegado(db,dados,{confirmarAssinatura:plano.assinatura,quiescenciaMs:0,aguardar:async()=>{
  await assert.rejects(bancoDoUsuario(db,'legado-titular'),/manutenção/);
  await db.doc('funcionarios/func-legada').update({alteradoNoTeste:true});
 }}),/mudaram/);
 assert.equal((await db.doc('migracoesGrupos/legado').get()).data().bloqueada,false);
 assert.equal((await db.collection('grupos').get()).size,0);
 const novo=await planejarMigracao(db,dados);
 await migrarLegado(db,dados,{confirmarAssinatura:novo.assinatura,quiescenciaMs:0,aguardar:async()=>{}});
 const grupo=await bancoDoUsuario(db,'legado-titular');assert.equal(grupo.grupoId,'casa-migrada');
 assert.equal((await grupo.doc('dias/func-legada_2026-10-20').get()).data().entrada,'08:00');
 assert.equal((await grupo.doc('comprasListas/compra/itens/arroz').get()).data().totalCentavos,5000);
 assert.equal((await grupo.doc('lembretes/cuidado/ocorrencias/dose').get()).data().concluidoPor,'legado-func');
 assert.equal((await db.doc('dias/func-legada_2026-10-20').get()).exists,true);
 assert.equal((await db.doc('users/legado-titular').get()).data().ativo,false);
 assert.equal((await grupo.doc('users/legado-titular').get()).data().ativo,true);
 assert.equal((await bridge.summary('target-mig','2026-10')).months.find(m=>m.month==='2026-10').totalCentavos,5000);
 await grupo.doc('comprasListas/nova').set({status:'finalizada',finalizadaPor:'legado-titular',totalCentavos:1000,finalizadaEm:new Date('2026-10-21T12:00:00Z')});
 await bancoDoGrupo(db,'outro-grupo').doc('comprasListas/nao-somar').set({status:'finalizada',finalizadaPor:'legado-titular',totalCentavos:99999,finalizadaEm:new Date('2026-10-21T12:00:00Z')});
 assert.equal((await bridge.summary('target-mig','2026-10')).months.find(m=>m.month==='2026-10').totalCentavos,6000);
 await assert.rejects(planejarMigracao(db,dados),/administrador ativo|em uso/);
});

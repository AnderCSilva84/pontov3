const test = require('node:test');
const assert = require('node:assert/strict');
test('pessoas e pets: atribuição, compartilhamento, supervisão e confirmação única', { skip: !process.env.FIRESTORE_EMULATOR_HOST }, async t => {
  assert.ok(process.env.GCLOUD_PROJECT?.startsWith('demo-'));
  const admin = require('../functions/node_modules/firebase-admin');
  const app = admin.initializeApp({ projectId: `${process.env.GCLOUD_PROJECT}-cuidados` }, 'cuidados');
  const db = app.firestore(); t.after(() => app.delete());
  const { operarLembretes, processarLembretes } = require('../functions/lembretes.cjs');
  const agora = Date.parse('2026-10-19T11:59:00Z'), devido = agora + 60000;
  for (const [id, perfil] of Object.entries({ adm: { role: 'admin', lembretesHabilitados: true }, x: { role: 'funcionario', babaCuidadora: true, funcionarioId: 'x' }, y: { role: 'funcionario', babaCuidadora: true, funcionarioId: 'y' }, bloqueado: { role: 'funcionario' } })) await db.doc(`users/${id}`).set({ ...perfil, nome: id, ativo: true });
  for (const id of ['x','y']) await db.doc(`funcionarios/${id}`).set({ ativo: true, escala: { segunda: { inicio: '08:00', fim: '17:00', cargaMin: 480 } } });
  const op = (operacao, dados = {}, uid = 'adm', instante = agora) => operarLembretes(db, { auth: { uid }, data: { ...dados, operacao } }, instante);
  const base = { titulo: 'Cuidado fictício', tipo: 'remedio', medicamento: 'Remédio fictício', posologia: 'Orientação de teste', horarios: ['09:00'], dataInicio: '2026-10-19', repeticao: 'diario' };
  let crianca, pet, lembrete, compartilhado;
  await t.test('somente admin cadastra; funcionários consultam apenas cadastros atribuídos', async () => {
    await assert.rejects(op('salvarCuidado', { nome: 'Teste', tipo: 'crianca', destinatarios: 'todos' }, 'x'), /administrador/);
    crianca = (await op('salvarCuidado', { nome: 'Criança fictícia', tipo: 'crianca', destinatarios: 'usuario', usuarioId: 'x' })).id;
    pet = (await op('salvarCuidado', { nome: 'Cão fictício', tipo: 'cao', destinatarios: 'todos' })).id;
    await assert.rejects(op('salvarCuidado', { nome: 'Teste', tipo: 'gato', destinatarios: 'usuario', usuarioId: 'bloqueado' }), /habilitado/);
    assert.equal((await op('listarCuidados', {}, 'x')).cuidados.length, 2);
    assert.deepEqual((await op('listarCuidados', {}, 'y')).cuidados.map(c => c.id), [pet]);
    await assert.rejects(op('listarCuidados', {}, 'bloqueado'), /autorizado/);
    lembrete = (await op('salvar', { ...base, cuidadoId: crianca, usuarioId: 'y', nomeCuidado: 'forjado' })).id;
    compartilhado = (await op('salvar', { ...base, cuidadoId: pet })).id;
    assert.equal((await op('listar', { visao: 'cuidados', cuidadoId: crianca }, 'x')).lembretes[0].nomeCuidado, 'Criança fictícia');
    await assert.rejects(op('listar', { visao: 'cuidados', cuidadoId: crianca }, 'y'), /autorizado/);
    assert.equal((await op('listar', {}, 'x')).lembretes.length, 0, 'consulta antiga não vaza vínculos desatualizados');
  });
  await t.test('reassignar muda acesso, PDF e destino sem copiar os lembretes', async () => {
    const c = (await op('listarCuidados')).cuidados.find(c => c.id === crianca);
    await op('salvarCuidado', { ...c, nome: 'Nome atualizado', usuarioId: 'y' });
    await assert.rejects(op('salvarCuidado', { ...c, usuarioId: 'x' }), /mudou/);
    await assert.rejects(op('listar', { visao: 'cuidados', cuidadoId: crianca }, 'x'), /autorizado/);
    const l = (await op('listar', { visao: 'cuidados', cuidadoId: crianca }, 'y')).lembretes[0];
    assert.equal(l.id, lembrete); assert.equal(l.nomeCuidado, 'Nome atualizado'); assert.equal(l.responsavelDescricao, 'y');
    await assert.rejects(op('concluir', { id: lembrete, ocorrenciaId: `1_${devido}` }, 'x', devido), /autorizado/);
    const envios = [];
    await processarLembretes(db, async (...args) => { envios.push(args); return 1; }, devido);
    assert.deepEqual(envios.filter(e => e[3].includes(lembrete)).map(e => e[4]).sort(), ['adm', 'y']);
    assert.deepEqual(envios.filter(e => e[3].includes(compartilhado)).map(e => e[4]).sort(), ['adm', 'x', 'y']);
    assert.ok(envios.every(e => e[6].ttl === 300));
    await Promise.all(['x','y','adm'].map(uid => op('concluir', { id: compartilhado, ocorrenciaId: `1_${devido}` }, uid, devido + 1000)));
    const registro = (await db.doc(`lembretes/${compartilhado}/ocorrencias/1_${devido}`).get()).data();
    assert.equal(registro.status, 'concluido'); assert.ok(['x','y','adm'].includes(registro.concluidaPor));
    assert.equal((await db.collection(`lembretes/${compartilhado}/ocorrencias`).get()).size, 1);
  });
  await t.test('fora do expediente somente administradores recebem; modo todos não habilita usuários', async () => {
    const id = (await op('salvar', { ...base, cuidadoId: pet, horarios: ['20:00'] })).id;
    const envios = [];
    await processarLembretes(db, async (...args) => { envios.push(args); return 1; }, Date.parse('2026-10-19T23:00:00Z'));
    assert.deepEqual(envios.filter(e => e[3].includes(id)).map(e => e[4]), ['adm']);
    assert.equal((await op('listar', { visao: 'cuidados' }, 'y')).lembretes.length, 3);
    await assert.rejects(op('listar', { visao: 'cuidados' }, 'bloqueado'), /autorizado/);
  });
});

test('lembretes explícitos: global, dedicado, autoria e edição sem depender do filtro', {skip:!process.env.FIRESTORE_EMULATOR_HOST}, async t=>{
  const admin=require('../functions/node_modules/firebase-admin');
  const app=admin.initializeApp({projectId:process.env.GCLOUD_PROJECT+'-destinos'},'destinos'); const db=app.firestore();t.after(()=>app.delete());
  const {operarLembretes,processarLembretes}=require('../functions/lembretes.cjs');
  const agora=Date.parse('2026-10-19T09:59:00Z'), devido=agora+60000;
  for(const [uid,p] of Object.entries({adm:{role:'admin',lembretesHabilitados:true},outro:{role:'admin',lembretesHabilitados:true},x:{role:'funcionario',babaCuidadora:true,funcionarioId:'x'},y:{role:'funcionario',babaCuidadora:true,funcionarioId:'y'},bloqueado:{role:'funcionario'}})) await db.doc(`users/${uid}`).set({...p,ativo:true,nome:uid});
  for(const uid of ['x','y']) await db.doc(`funcionarios/${uid}`).set({ativo:true,escala:{segunda:{inicio:'08:00',fim:'17:00',cargaMin:480}}});
  const op=(operacao,d={},uid='adm',ms=agora)=>operarLembretes(db,{auth:{uid},data:{operacao,...d}},ms);
  const base={titulo:'Aviso novo',tipo:'outro',horarios:['07:00'],dataInicio:'2026-10-19',repeticao:'diario',destinatarioCuidado:'crianca',nomeCuidado:'Paciente teste'};
  const global=(await op('salvar',{...base,destinatarios:'todos',criadaPor:'y',criadaPorNome:'Forjado'})).id;
  const dedicado=(await op('salvar',{...base,destinatarios:'usuario',usuarioId:'x'})).id;
  const todos=(await op('listar',{visao:'cuidados'})).lembretes;
  assert.equal(todos.length,2);assert.equal(todos.find(l=>l.id===global).criadaPorNome,'adm');assert.equal(todos.find(l=>l.id===global).destinatarios,'todos');
  assert.ok(todos.every(l=>l.criadaEmMs && l.criadaPor==='adm'));
  assert.equal((await op('listar',{visao:'cuidados'},'x')).lembretes.length,2);
  assert.deepEqual((await op('listar',{visao:'cuidados'},'y')).lembretes.map(l=>l.id),[global]);
  await assert.rejects(op('salvar',{...base,destinatarios:'usuario',usuarioId:'bloqueado'}),/Habilite/);
  await assert.rejects(op('concluir',{id:dedicado,ocorrenciaId:`1_${devido}`},'y',devido),/autorizado/);
  await op('salvar',{...base,id:dedicado,versao:1,destinatarios:'usuario',usuarioId:'y'},'outro');
  assert.equal((await op('listar',{visao:'cuidados'},'y')).lembretes.find(l=>l.id===dedicado).criadaPorNome,'adm');
  assert.equal((await op('listar',{visao:'cuidados'},'x')).lembretes.length,1);
  const envios=[];await processarLembretes(db,async(...args)=>{envios.push(args);return 1},devido);
  assert.deepEqual(envios.filter(e=>e[3].includes(global)).map(e=>e[4]).sort(),['adm','outro']);
  assert.deepEqual(envios.filter(e=>e[3].includes(dedicado)).map(e=>e[4]).sort(),['adm','outro']);
  await op('concluir',{id:global,ocorrenciaId:`1_${devido}`},'y',devido);
  await op('pausar',{id:global,versao:1,ativo:false});await op('pausar',{id:global,versao:2,ativo:true});
  const c=(await op('salvarCuidado',{nome:'Pessoa vinculada',tipo:'crianca',destinatarios:'usuario',usuarioId:'x'})).id;
  const vinculado=(await op('salvar',{...base,cuidadoId:c,destinatarios:'usuario',usuarioId:'y'})).id;
  assert.ok((await op('listar',{visao:'cuidados'},'y')).lembretes.some(l=>l.id===vinculado));
  assert.ok(!(await op('listar',{visao:'cuidados'},'x')).lembretes.some(l=>l.id===vinculado));
});

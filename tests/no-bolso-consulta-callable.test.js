import test from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import process from 'node:process';
import { initializeApp, deleteApp } from 'firebase/app';
import { getAuth, connectAuthEmulator, createUserWithEmailAndPassword, deleteUser } from 'firebase/auth';
import { getFunctions, connectFunctionsEmulator, httpsCallable } from 'firebase/functions';
const require = createRequire(import.meta.url);
test('consulta No Bolso por HTTP callable autentica e recusa comandos de escrita', { skip: process.env.AP1303_TEST_CALLABLE !== '1' }, async t => {
  assert.equal(process.env.GCLOUD_PROJECT, 'demo-ap1303');
  const admin = require('../functions/node_modules/firebase-admin');
  const servidor = admin.initializeApp({ projectId: 'demo-ap1303' }, 'http-consulta');
  const app = initializeApp({ projectId: 'demo-ap1303', apiKey: 'demo-key' }, 'http-consulta');
  const auth = getAuth(app); connectAuthEmulator(auth, 'http://127.0.0.1:9098', { disableWarnings: true });
  const functions = getFunctions(app); connectFunctionsEmulator(functions, '127.0.0.1', 5007);
  t.after(async () => { if (auth.currentUser) await deleteUser(auth.currentUser); await deleteApp(app); await servidor.delete(); });
  const chamada = httpsCallable(functions, 'noBolsoConsulta', { timeout: 20000 });
  await assert.rejects(chamada({ consulta: 'rankings' }), { code: 'functions/unauthenticated' });
  const uid = (await createUserWithEmailAndPassword(auth, `consulta-${Date.now()}@example.test`, 'Ficticia-123456')).user.uid;
  const grupo = `consulta-http-${uid}`, db = servidor.firestore();
  await db.doc(`grupos/${grupo}`).set({ ativo: true });
  await db.doc(`vinculosUsuarios/${uid}`).set({ ativo: true, grupoId: grupo });
  await db.doc(`grupos/${grupo}/users/${uid}`).set({ ativo: true, role: 'admin' });
  await db.doc(`grupos/${grupo}/comprasPrecos/preco`).set({ produtoId: 'teste', nomeSnapshot: 'Produto fictício', apresentacao: '1 kg', unidadeCompra: 'kg', supermercadoId: 'loja', supermercadoNome: 'Loja fictícia (Belém)', quantidadeComprada: 1, precoUnitarioCentavos: 100, compradoEm: new Date() });
  const grantsAntes = (await db.collection('noBolsoGrants').get()).size;
  assert.equal((await chamada({ consulta: 'produto', produtoId: 'teste' })).data.ofertas[0].unidade, 'kg');
  for (const data of [{ consulta: 'vincular' }, { consulta: 'importar' }, { consulta: 'rankings', grupoId: 'outro' }]) await assert.rejects(chamada(data), { code: 'functions/invalid-argument' });
  assert.equal((await db.collection('noBolsoGrants').get()).size, grantsAntes);
});

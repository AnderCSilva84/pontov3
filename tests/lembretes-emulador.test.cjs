const test = require('node:test');
const assert = require('node:assert/strict');
test('lembretes: permissões, dose, agendamento e envio por destinatária', { skip: !process.env.FIRESTORE_EMULATOR_HOST }, async t => {
  assert.ok(process.env.GCLOUD_PROJECT?.startsWith('demo-'));
  const admin = require('../functions/node_modules/firebase-admin');
  admin.initializeApp({ projectId: process.env.GCLOUD_PROJECT });
  const db = admin.firestore();
  const { operarLembretes, processarLembretes } = require('../functions/lembretes.cjs');
  const { enviarPush } = require('../functions/push.cjs');
  const { initializeApp, deleteApp } = await import('firebase/app');
  const { getAuth, connectAuthEmulator, createUserWithEmailAndPassword, signOut } = await import('firebase/auth');
  const { getFirestore, connectFirestoreEmulator, doc, getDoc, getDocs, collection, query, where, setDoc, updateDoc, terminate } = await import('firebase/firestore');
  const app = initializeApp({ projectId: process.env.GCLOUD_PROJECT, apiKey: 'demo-key' }, 'lembretes-teste');
  const auth = getAuth(app); connectAuthEmulator(auth, 'http://127.0.0.1:9098', { disableWarnings: true });
  const client = getFirestore(app); connectFirestoreEmulator(client, '127.0.0.1', 8877);
  const uid = (await createUserWithEmailAndPassword(auth, 'cuidadora-lembretes@example.test', 'senha-teste-123')).user.uid;
  t.after(async () => { await signOut(auth); await terminate(client); await deleteApp(app); await admin.app().delete(); });
  await db.doc('users/lem-admin').set({ role: 'admin', ativo: true });
  await db.doc(`users/${uid}`).set({ role: 'funcionario', babaCuidadora: true, funcionarioId: uid, ativo: true });
  await db.doc(`funcionarios/${uid}`).set({ ativo: true, escala: { segunda: { inicio: '00:00', fim: '23:59', cargaMin: 480 } } });
  await db.doc('users/lem-outra').set({ role: 'funcionario', babaCuidadora: true, ativo: true });
  const inicio = Date.parse('2026-10-19T14:59:00Z'), horario = Date.parse('2026-10-19T15:00:00Z');
  const base = { titulo: 'Cuidado fictício', tipo: 'remedio', medicamento: 'Medicamento de teste', posologia: 'Orientação fictícia informada no cadastro', horario: '12:00', dataInicio: '2026-10-19', repeticao: 'uma_vez', usuarioId: uid };
  const op = (operacao, dados, usuario = 'lem-admin', agora = inicio) => operarLembretes(db, { auth: { uid: usuario }, data: { ...dados, operacao } }, agora);
  let id;
  await t.test('duas doses avisam e concluem separadamente sem perder a primeira pendente', async () => {
    const novo = (await op('salvar', { ...base, horarios: ['12:00', '20:00'], repeticao: 'diario' })).id;
    const envios = [];
    const enviar = async (...args) => { envios.push(args); return 1; };
    await processarLembretes(db, enviar, horario);
    await processarLembretes(db, enviar, horario + 8 * 3600000);
    assert.equal(envios.length, 2);
    assert.match(envios[1][1], /20:00/);
    const l = (await op('listar', {}, uid, horario + 8 * 3600000)).lembretes.find(l => l.id === novo);
    assert.equal(l.ocorrencias.length, 2);
    const primeira = l.ocorrencias.find(o => o.horarioMs === horario);
    const segunda = l.ocorrencias.find(o => o.horarioMs !== horario);
    const link=new URL(envios[0][2],'https://example.test');
    assert.equal(link.searchParams.get('lembreteId'),novo);assert.equal(link.searchParams.get('ocorrenciaId'),primeira.id);assert.equal(link.searchParams.get('destinatario'),uid);
    const consulta=await op('consultarOcorrencia',{id:novo,ocorrenciaId:primeira.id},uid,horario+8*3600000);
    assert.equal(consulta.concluida,false);assert.equal(consulta.posologia,base.posologia);
    await assert.rejects(op('consultarOcorrencia',{id:novo,ocorrenciaId:primeira.id},'lem-outra',horario),/autorizado/);
    await op('concluir', { id: novo, ocorrenciaId: primeira.id }, uid, horario + 8 * 3600000);
    await op('concluir', { id: novo, ocorrenciaId: primeira.id }, uid, horario + 8 * 3600000 + 60000);
    assert.equal((await op('consultarOcorrencia',{id:novo,ocorrenciaId:primeira.id},uid,horario+8*3600000)).concluida,true);
    let registros = (await op('listar', {}, uid)).lembretes.find(l => l.id === novo).ocorrencias;
    assert.equal(registros.find(o => o.id === primeira.id).status, 'concluido');
    assert.equal(registros.find(o => o.id === segunda.id).status, 'enviado');
    await op('concluir', { id: novo, ocorrenciaId: segunda.id }, uid, horario + 8 * 3600000);
    assert.equal((await db.doc(`lembretes/${novo}`).get()).data().proximoDisparoEm.toMillis(), horario + 86400000);
    await db.doc(`lembretes/${novo}`).delete();
  });
  await t.test('somente admin cadastra, cuidadora lê apenas seus lembretes e não pode se habilitar', async () => {
    await assert.rejects(op('salvar', base, uid), /administrador/);
    id = (await op('salvar', base)).id;
    const outro = (await op('salvar', { ...base, usuarioId: 'lem-outra', horario: '23:00' })).id;
    assert.equal((await op('listar', {}, uid)).lembretes[0].posologia, base.posologia);
    await assert.rejects(op('listar', { usuarioId: 'lem-outra' }, uid), /autorizado/);
    await assert.rejects(getDoc(doc(client, 'lembretes', id)), /permission/i);
    await assert.rejects(getDocs(query(collection(client, 'lembretes'), where('usuarioId', '==', uid))), /permission/i);
    await assert.rejects(getDoc(doc(client, 'lembretes', outro)), /permission/i);
    await assert.rejects(getDocs(collection(client, 'lembretes')), /permission/i);
    await assert.rejects(setDoc(doc(client, 'lembretes', 'forjado'), base), /permission/i);
    await assert.rejects(updateDoc(doc(client, 'users', uid), { babaCuidadora: false }), /permission/i);
    await db.doc(`users/${uid}`).update({ babaCuidadora: false });
    await assert.rejects(getDoc(doc(client, 'lembretes', id)), /permission/i);
    await assert.rejects(op('listar', {}, uid), /autorizado/);
    await assert.rejects(op('salvar', base), /Babá/);
    await db.doc(`users/${uid}`).update({ babaCuidadora: true });
  });
  await t.test('agendador envia somente à destinatária uma vez com sobreposição e preserva posologia', async () => {
    await db.doc('pushDispositivos/lem-dispositivo').set({ uid, token: 'token-ficticio-cuidadora' });
    await db.doc('pushDispositivos/lem-outro-dispositivo').set({ uid: 'lem-outra', token: 'token-ficticio-outro' });
    const mensagens = [];
    const falsoAdmin = { firestore: () => db, messaging: () => ({ sendEach: async lote => { mensagens.push(...lote); return { responses: lote.map(() => ({ success: true })) }; } }) };
    const enviar = (...args) => enviarPush(falsoAdmin, ...args);
    await Promise.all([processarLembretes(db, enviar, horario), processarLembretes(db, enviar, horario)]);
    await processarLembretes(db, enviar, horario + 60000);
    assert.equal(mensagens.length, 1);
    assert.equal(mensagens[0].data.uid, uid);
    const destino=new URL(mensagens[0].data.url,'https://example.test');
    assert.equal(destino.pathname,'/lembretes');assert.equal(destino.searchParams.get('lembreteId'),id);assert.equal(destino.searchParams.get('destinatario'),uid);
    assert.equal(mensagens[0].webpush.headers.TTL, '300');
    assert.equal(mensagens[0].webpush.headers.Urgency, 'high');
    const l = (await db.doc(`lembretes/${id}`).get()).data();
    assert.equal(await enviar('Lembrete de cuidado', 'Repetição de teste', '/lembretes', `lembrete:${id}:${l.ultimaOcorrencia.id}`, uid, false, { contarConfirmados: true }), 1);
    assert.equal(mensagens.length, 1);
    assert.equal(l.ultimaOcorrencia.status, 'enviado');
    assert.equal(l.proximoDisparoEm, null);
    assert.equal(l.posologia, base.posologia);
    await assert.rejects(op('concluir', { id, ocorrenciaId: l.ultimaOcorrencia.id }, 'lem-outra', horario), /autorizado/);
    await op('concluir', { id, ocorrenciaId: l.ultimaOcorrencia.id }, uid, horario + 60000);
    await op('concluir', { id, ocorrenciaId: l.ultimaOcorrencia.id }, uid, horario + 120000);
    const concluido = (await db.doc(`lembretes/${id}`).get()).data().ultimaOcorrencia;
    assert.equal(concluido.status, 'concluido'); assert.equal(concluido.concluidaPor, uid); assert.equal(concluido.concluidaEmMs, horario + 60000);
  });
  await t.test('realização antes da rodada do agendador impede aviso e mantém próximo horário recorrente', async () => {
    const novo = (await op('salvar', { ...base, horario: '12:02', repeticao: 'diario' })).id;
    const ms = horario + 120000, ocorrenciaId = `1_${ms}`;
    await assert.rejects(op('concluir', { id: novo, ocorrenciaId }, uid, ms - 1000), /Atualize/);
    await op('concluir', { id: novo, ocorrenciaId }, uid, ms);
    let envios = 0;
    await processarLembretes(db, async () => { envios++; return 1; }, ms);
    assert.equal(envios, 0);
    const l = (await db.doc(`lembretes/${novo}`).get()).data();
    assert.equal(l.proximoDisparoEm.toMillis(), ms + 86400000);
    assert.equal(l.ultimaOcorrencia.status, 'concluido');
    await assert.rejects(op('pausar', { id: novo, versao: 1, ativo: false }, uid), /administrador/);
    await op('pausar', { id: novo, versao: 1, ativo: false });
    assert.equal((await db.doc(`lembretes/${novo}`).get()).data().proximoDisparoEm, null);
    await assert.rejects(op('salvar', { ...base, id: novo, versao: 1 }), /mudou/);
  });
  await t.test('falha de envio tenta novamente e revogação do acesso bloqueia disparos', async () => {
    const novo = (await op('salvar', { ...base, horario: '12:05' })).id;
    await processarLembretes(db, async () => { throw Error('falha fictícia'); }, horario + 300000);
    assert.ok((await db.doc(`lembretes/${novo}`).get()).data().proximoDisparoEm);
    let envios = 0;
    await processarLembretes(db, async () => { envios++; return 1; }, horario + 360000);
    assert.equal(envios, 1);
    const semAcesso = (await op('salvar', { ...base, horario: '12:07' })).id;
    await db.doc(`users/${uid}`).update({ babaCuidadora: false });
    await processarLembretes(db, async () => { throw Error('não deve chamar'); }, horario + 420000);
    assert.equal((await db.doc(`lembretes/${semAcesso}`).get()).data().ultimaOcorrencia.status, 'sem_acesso');
  });
  await t.test('horários antigos não geram aviso atrasado nem são marcados como realizados', async () => {
    await db.doc(`users/${uid}`).update({ babaCuidadora: true });
    const novo = (await op('salvar', { ...base, horario: '12:09' })).id;
    await processarLembretes(db, async () => { throw Error('não deve enviar aviso antigo'); }, horario + 30 * 60000);
    const l = (await db.doc(`lembretes/${novo}`).get()).data();
    assert.equal(l.ultimaOcorrencia.status, 'atrasado');
    assert.equal(l.proximoDisparoEm, null);
    await assert.rejects(operarLembretes(db, { data: { operacao: 'concluir', id: novo } }), /Entre no app/);
  });
  await t.test('admin habilitado recebe à noite; funcionária fora da escala não recebe; doses preservam cuidado e autor', async () => {
    const tarde = horario + 9 * 3600000;
    await db.doc(`funcionarios/${uid}`).update({ escala: { segunda: { inicio: '08:00', fim: '17:00', cargaMin: 480 } } });
    const funcionario = (await op('salvar', { ...base, horario: '21:00' })).id;
    await assert.rejects(op('salvar', { ...base, usuarioId: 'lem-admin', horario: '21:00' }), /Habilite/);
    await db.doc('users/lem-admin').update({ lembretesHabilitados: true, nome: 'Admin fictício' });
    const adm = (await op('salvar', { ...base, usuarioId: 'lem-admin', horario: '21:00', destinatarioCuidado: 'cao', nomeCuidado: 'Pet fictício' })).id;
    const envios = [];
    await processarLembretes(db, async (...args) => { envios.push(args); return 1; }, tarde);
    assert.equal(envios.length, 2); assert.ok(envios.every(e => e[4] === 'lem-admin'));
    assert.equal((await db.doc(`lembretes/${funcionario}`).get()).data().ultimaOcorrencia.status, 'fora_expediente');
    assert.equal((await db.doc(`lembretes/${funcionario}`).get()).data().ultimaOcorrencia.avisosAdministradores, true);
    const antes = (await db.doc(`lembretes/${adm}`).get()).data();
    await op('concluir', { id: adm, ocorrenciaId: antes.ultimaOcorrencia.id }, 'lem-admin', tarde + 60000);
    const depois = (await db.doc(`lembretes/${adm}/ocorrencias/${antes.ultimaOcorrencia.id}`).get()).data();
    assert.equal(depois.status, 'concluido'); assert.equal(depois.notificacaoStatus, 'enviado');
    const plano = (await op('listar', { usuarioId: 'lem-admin' })).lembretes;
    assert.equal(plano[0].nomeCuidado, 'Pet fictício'); assert.equal(depois.concluidaPor, 'lem-admin');
    await op('excluir', { id: adm, versao: 1 });
    assert.equal((await op('listar', { usuarioId: 'lem-admin' })).lembretes.length, 0);
  });
  await t.test('falha no aparelho da funcionária não bloqueia admin e a repetição não duplica o aviso já aceito', async () => {
    await db.doc('pushDispositivos/lem-admin-dispositivo').set({ uid: 'lem-admin', token: 'token-ficticio-admin' });
    await db.doc('users/lem-admin-inativo').set({ role: 'admin', ativo: false, lembretesHabilitados: true });
    await db.doc('pushDispositivos/lem-admin-inativo').set({ uid: 'lem-admin-inativo', token: 'token-ficticio-inativo' });
    const novo = (await op('salvar', { ...base, horario: '12:45' })).id;
    const aceitos = []; let falhou = false;
    const falsoAdmin = { firestore: () => db, messaging: () => ({ sendEach: async lote => ({ responses: lote.map(m => { if (m.data.uid === uid && !falhou) { falhou = true; return { success: false, error: { code: 'messaging/internal-error' } }; } aceitos.push(m.data.uid); return { success: true }; }) }) }) };
    await processarLembretes(db, (...args) => enviarPush(falsoAdmin, ...args), horario + 45 * 60000);
    assert.deepEqual(aceitos, ['lem-admin']);
    await processarLembretes(db, (...args) => enviarPush(falsoAdmin, ...args), horario + 46 * 60000);
    assert.deepEqual(aceitos, ['lem-admin', uid]);
    assert.equal((await db.doc(`lembretes/${novo}`).get()).data().ultimaOcorrencia.avisosAdministradores, true);
  });
  await t.test('fim do expediente é revalidado no instante do envio e limita a expiração do aviso', async () => {
    const ms = Date.parse('2026-10-19T16:59:00-03:00');
    const primeiro = (await op('salvar', { ...base, horario: '16:59' })).id;
    const envios = [];
    await processarLembretes(db, async (...args) => { envios.push(args); return 1; }, ms, () => ms + 60000);
    assert.ok(envios.every(e => e[4] === 'lem-admin'));
    assert.equal((await db.doc(`lembretes/${primeiro}`).get()).data().ultimaOcorrencia.status, 'fora_expediente');
    await op('salvar', { ...base, horario: '16:59' });
    envios.length = 0;
    await processarLembretes(db, async (...args) => { envios.push(args); return 1; }, ms, () => ms + 30000);
    const funcionaria = envios.find(e => e[4] === uid);
    assert.ok(funcionaria); assert.equal(funcionaria[6].ttl, 29);
  });
});

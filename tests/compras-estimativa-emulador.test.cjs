const test = require('node:test'), assert = require('node:assert/strict');
test('estimativa autenticada consulta preços reais do emulador sem escrever em listas, histórico ou despesas', { skip: !process.env.FIRESTORE_EMULATOR_HOST }, async t => {
  assert.ok(process.env.GCLOUD_PROJECT?.startsWith('demo-'));
  const admin = require('../functions/node_modules/firebase-admin');
  const { estimarCompras } = require('../functions/compras-estimativa.cjs');
  const app = admin.initializeApp({ projectId: `${process.env.GCLOUD_PROJECT}-estimativa` }, 'estimativa');
  const db = app.firestore(); t.after(() => app.delete());
  await db.doc('users/est-admin').set({ role: 'admin', ativo: true });
  await db.doc('users/est-func').set({ role: 'funcionario', ativo: true });
  await db.doc('users/est-bloqueado').set({ role: 'admin', ativo: false });
  await db.doc('comprasListas/est-lista').set({ titulo: 'Estimativa fictícia', status: 'rascunho' });
  const item = { produtoId: 'est-produto', apresentacao: 'A granel', unidadeCompra: 'kg', quantidadePlanejada: 1.375, estado: 'pendente' };
  await db.doc('comprasListas/est-lista/itens/a').set(item);
  await db.doc('comprasListas/est-lista/itens/b').set({ ...item, produtoId: 'est-sem-preco' });
  const preco = { ...item, valido: true, supermercadoNome: 'Mercado fictício', compradoEm: admin.firestore.Timestamp.fromMillis(1000), precoUnitarioCentavos: 699 };
  await db.doc('comprasPrecos/est-preco-1').set(preco);
  await db.doc('comprasPrecos/est-preco-2').set({ ...preco, compradoEm: admin.firestore.Timestamp.fromMillis(2000), precoUnitarioCentavos: 899 });
  await db.doc('comprasPrecos/est-invalidado').set({ ...preco, valido: false, compradoEm: admin.firestore.Timestamp.fromMillis(3000), precoUnitarioCentavos: 99999 });
  await db.doc('comprasPrecos/est-outro-tamanho').set({ ...preco, apresentacao: 'Caixa', compradoEm: admin.firestore.Timestamp.fromMillis(4000), precoUnitarioCentavos: 99999 });
  const consulta = (uid, listaId = 'est-lista') => estimarCompras(db, { auth: { uid }, data: { listaId } }, 5000);
  await assert.rejects(estimarCompras(db, {}), /Entre no app/);
  await assert.rejects(consulta('est-bloqueado'), /autorizado/);
  await assert.rejects(consulta('est-admin', '../errada'), /inválida/);
  const resultado = await consulta('est-admin');
  assert.equal(resultado.referencias.a.ultimoCentavos, 899); assert.equal(resultado.referencias.a.mediaCentavos, 799); assert.equal(resultado.referencias.a.amostra, 2);
  assert.equal(resultado.referencias.b, null);
  assert.deepEqual(await consulta('est-func'), resultado);
  assert.deepEqual((await db.doc('comprasListas/est-lista/itens/a').get()).data(), item);
  await db.doc('comprasListas/est-lista/itens/a').update({ estado: 'comprado_sem_preco' });
  assert.equal((await consulta('est-admin')).referencias.a.ultimoCentavos, 899);
  assert.equal((await db.doc('comprasListas/est-lista/itens/a').get()).data().precoUnitarioCentavos, undefined);
  assert.equal((await db.doc('comprasListas/est-lista').get()).data().totalCentavos, undefined);
  await db.doc('comprasPrecos/est-preco-2').update({ valido: false });
  assert.equal((await consulta('est-admin')).referencias.a.ultimoCentavos, 699);
});
